from pathlib import Path
from langchain_community.document_loaders import TextLoader


#=============================================================================================================
# Create Sample text file
#=============================================================================================================

file_path = Path(__file__).resolve().parent/"student_rules.txt"

file_path.write_text("Students must carry their ID card.\n"
                     "Classes starts at 9 AM. \n"
                     "Mobile  phones are not allowed.\n",
                     encoding='utf-8')

#=============================================================================================================
# Create Text Loader
#=============================================================================================================

loader = TextLoader(
    file_path=str(file_path),
    encoding='utf-8'
)

#=============================================================================================================
# Load Documents
#=============================================================================================================

documents = loader.load()

#=============================================================================================================
# Display total documents
#=============================================================================================================

print("\n Total documents:", len(documents))


#=============================================================================================================
# Access first document 
#=============================================================================================================

document = documents[0]

#=============================================================================================================
# Display content
#=============================================================================================================

print("\n page content")
print("========================================================================================")
print(document.page_content.strip())


#=============================================================================================================
# Display source
#=============================================================================================================

print("\n Document source")
print("========================================================================================")
print(document.metadata['source']) # full path
print("========================================================================================")
print(Path(document.metadata['source']).name) # relative path i.e just file name