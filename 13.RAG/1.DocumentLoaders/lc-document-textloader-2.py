from os import name
from pathlib import Path
from langchain_community.document_loaders import TextLoader

#======================================================================================================
# Create sample text file
#======================================================================================================

file_path = Path(__file__).resolve().parent/'library_rules.txt'
content = (
    "The Library opens at 8 am.\n"
    "The Library closes at 6 pm.\n"
)
file_path.write_text(content,encoding='utf-8')

#======================================================================================================
# Create text loader
#======================================================================================================

loader = TextLoader(file_path=str(file_path),encoding='utf-8')

#======================================================================================================
# load documents
#======================================================================================================

documents = loader.load()

#======================================================================================================
# Check return type
#======================================================================================================

print("Return type of documents")
print(type(documents))
print("==============================================================================")
print(type(documents).__name__)


#======================================================================================================
# Check total documents
#======================================================================================================

print("\n Total documents:",len(documents))

#======================================================================================================
# Access document
#======================================================================================================
document  = documents[0]

print("==================================================================================")
print("\n Document type")
print(type(document).__name__)


#======================================================================================================
# Display source meta data
#======================================================================================================

print("\n Source file")
print(Path(document.metadata['source']).name)

#======================================================================================================
# Add custom meta data
#======================================================================================================

document.metadata['department']='Administration'

#======================================================================================================
# Display custom meta data
#======================================================================================================

print("\n Department")
print(Path(document.metadata['department']).name)


#======================================================================================================
# Check original file
#======================================================================================================

print("\n Original file unchanged")
print("=============================================================================================")
print(file_path.read_text(encoding='utf-8')==content)



# TextLoader creates Document objects with source metadata.
# We can extend the metadata without changing the original text file.
